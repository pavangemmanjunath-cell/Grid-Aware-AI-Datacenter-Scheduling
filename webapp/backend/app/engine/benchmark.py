"""Benchmark loading: the 168-hour feature table the scheduler consumes.

The shipped benchmark (``data/research_benchmark_168h.csv``) is a deterministic,
synthetic week generated by ``matlab/qh2dc_build_benchmark.m``.  It is read here
exactly as the MATLAB and Python reference implementations read it, including the
same validation gate (``qh2dc_load_benchmark.m``).
"""
from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

import numpy as np
import pandas as pd

CANDIDATE_OFFSETS = (0, 3, 7)  # hours after the baseline slot; offset 0 is the baseline


@dataclass(frozen=True)
class Benchmark:
    hour_of_day: np.ndarray
    day: np.ndarray
    fixed: np.ndarray          # latency-sensitive demand [MW]
    flex: np.ndarray           # delay-tolerant bundle power in its baseline slot [MW]
    solar: np.ndarray
    wind: np.ndarray
    renewable: np.ndarray
    carbon: np.ndarray         # grid carbon intensity [kgCO2/MWh]
    cap_nonfirm: np.ndarray
    cap_phased: np.ndarray

    @property
    def T(self) -> int:
        return len(self.fixed)

    @property
    def bundle_hours(self) -> np.ndarray:
        return np.where(self.flex > 0)[0]

    @property
    def bundle_energy(self) -> np.ndarray:
        return self.flex[self.bundle_hours]

    def candidates(self, offsets: tuple[int, ...] = CANDIDATE_OFFSETS) -> list[list[int]]:
        return [[min(self.T - 1, int(t0) + o) for o in offsets] for t0 in self.bundle_hours]

    def scaled(self, demand: float = 1.0, solar: float = 1.0, wind: float = 1.0) -> Benchmark:
        """Return a copy with AI demand, solar and wind output scaled (what-if analysis)."""
        sol, wnd = self.solar * solar, self.wind * wind
        return Benchmark(
            hour_of_day=self.hour_of_day, day=self.day,
            fixed=self.fixed * demand, flex=self.flex * demand,
            solar=sol, wind=wnd, renewable=sol + wnd, carbon=self.carbon,
            cap_nonfirm=self.cap_nonfirm, cap_phased=self.cap_phased,
        )


class BenchmarkError(ValueError):
    """Raised when the benchmark file fails the validation gate."""


def _validate(df: pd.DataFrame) -> None:
    if len(df) != 168:
        raise BenchmarkError(f"expected 168 hourly rows, found {len(df)}")
    if df.isna().any().any():
        raise BenchmarkError("benchmark contains missing values")
    if not np.allclose(df.total_baseline_load_MW, df.fixed_ai_load_MW + df.baseline_flexible_load_MW, atol=1e-9):
        raise BenchmarkError("total_baseline_load_MW != fixed + flexible")
    if not np.allclose(df.renewable_MW, df.solar_MW + df.wind_MW, atol=1e-9):
        raise BenchmarkError("renewable_MW != solar + wind")


@lru_cache(maxsize=4)
def load_benchmark(data_dir: str) -> Benchmark:
    df = pd.read_csv(Path(data_dir) / "research_benchmark_168h.csv")
    _validate(df)
    return Benchmark(
        hour_of_day=df.hour_of_day.to_numpy(int), day=df.day.to_numpy(int),
        fixed=df.fixed_ai_load_MW.to_numpy(float), flex=df.baseline_flexible_load_MW.to_numpy(float),
        solar=df.solar_MW.to_numpy(float), wind=df.wind_MW.to_numpy(float),
        renewable=df.renewable_MW.to_numpy(float), carbon=df.grid_carbon_kgCO2_per_MWh.to_numpy(float),
        cap_nonfirm=df.nonfirm_connection_cap_MW.to_numpy(float),
        cap_phased=df.phased_connection_cap_MW.to_numpy(float),
    )
