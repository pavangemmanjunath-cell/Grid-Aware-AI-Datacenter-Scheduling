EXPLORATORY_DISCLAIMER = (
    "Exploratory what-if run on the synthetic 168-hour benchmark. These numbers are NOT results "
    "of the paper and have not been peer reviewed. The published figures are the R0-R5 scenarios "
    "with the default parameters."
)


def _r(a, nd=4):
    return [None if not math.isfinite(v) else round(float(v), nd) for v in np.asarray(a, dtype=float)]


def series_of(s: Schedule) -> HourlySeries:
    return HourlySeries(grid_import_MW=_r(s.pg), electrolyser_MW=_r(s.pe), fuel_cell_MW=_r(s.pf),
                        curtailed_MW=_r(s.pc), h2_inventory_MWh=_r(s.h), flexible_load_MW=_r(s.flex_load),
                        connection_cap_MW=_r(s.cap, 3))


@lru_cache(maxsize=2)
def published_table(data_dir: str) -> dict[str, dict[str, float]]:
    with open(Path(data_dir) / "research_results_gridflex.csv", newline="") as fh:
        return {row["scenario"].split()[0]: {k: float(v) for k, v in row.items() if k != "scenario"}
                for row in csv.DictReader(fh)}


@lru_cache(maxsize=2)
def solved_scenarios(data_dir: str) -> dict:
    """Solve R0-R5 once per process (about 1-2 s) and cache the schedules."""
    b = load_benchmark(data_dir)
    return {k: run_scenario(b, k) for k in SCENARIOS}


def run_whatif(data_dir: str, req: WhatIfRequest, progress) -> WhatIfResult:
    """Solve one user-configured campus. Defaults reproduce the paper's R2/R3/R4/R5 exactly."""
    base = load_benchmark(data_dir)
    b: Benchmark = base.scaled(demand=req.demand_scale, solar=req.solar_scale, wind=req.wind_scale)
    cfg = replace(PlantConfig(), electrolyser_mw=req.electrolyser_mw, fuel_cell_mw=req.fuel_cell_mw,
                  h2_max_mwh=req.h2_max_mwh, h2_init_mwh=req.h2_init_mwh, eta_el=req.eta_el, eta_fc=req.eta_fc,
                  candidate_offsets=tuple(req.candidate_offsets_h), time_limit_s=30.0)
    peak = float((b.fixed + b.flex).max())
    if req.mode in (WhatIfMode.min_uniform, WhatIfMode.min_uniform_flexible):
        flexible = req.mode == WhatIfMode.min_uniform_flexible
        # grid-only operation at the peak load is always feasible, so the search interval brackets the answer
        cap = min_uniform_capacity(b, cfg, use_h2=True, flexible=flexible, hi=max(16.0, peak + 0.1), progress=progress)
        s = solve_dispatch(b, np.full(b.T, cap), cfg, use_h2=True, flexible=flexible) if cap is not None else None
        reported = cap
    else:
        if req.mode == WhatIfMode.nonfirm:
            env = nonfirm_envelope(b, req.nonfirm_normal_mw, req.nonfirm_reduced_mw, req.nonfirm_start_hour,
                                   req.nonfirm_end_hour)
        else:
            env = np.repeat(np.asarray(req.phased_levels_mw, dtype=float), int(np.ceil(b.T / 3)))[: b.T]
        s = solve_dispatch(b, env, cfg, use_h2=True, flexible=req.workload_flexibility)
        reported = float(s.pg.max()) if s is not None else None
    progress(1.0)
    if s is None:
        return WhatIfResult(disclaimer=EXPLORATORY_DISCLAIMER, feasible=False, connection_capacity_MW=None,
                            reduction_vs_grid_only_pct=None, metrics=None, bundle_delays_h=None, series=None)
    if not all(math.isfinite(v) for v in s.metrics.values()):
        raise ValueError("non-finite metric in the solved schedule")
    return WhatIfResult(disclaimer=EXPLORATORY_DISCLAIMER, feasible=True, connection_capacity_MW=round(reported, 6),
                        reduction_vs_grid_only_pct=round(100 * (1 - reported / peak), 4),
                        metrics=Metrics(**s.metrics), bundle_delays_h=[int(x) for x in s.delays], series=series_of(s))


def provenance(data_dir: str) -> dict:
    files = ("research_benchmark_168h.csv", "research_flexible_jobs.csv", "research_results_gridflex.csv",
             "verification_summary.json")
    return {
        "data_files": {f: hashlib.sha256((Path(data_dir) / f).read_bytes()).hexdigest() for f in files},
        "benchmark": "Deterministic synthetic 168-hour week generated by matlab/qh2dc_build_benchmark.m "
                     "(seed 20260430). Not operator data.",
        "reference_implementations": ["matlab/ (MATLAB, published reference)",
                                      "verify/verify_python.py (independent Python/SciPy cross-check)"],
        "engine": "webapp/backend/app/engine (SciPy milp / HiGHS); parity-tested against data/",
    }


def public_datasets(data_dir: str) -> list[dict]:
    """Catalogue in data/public_datasets.json (links and licences verified online)."""
    doc = json.loads((Path(data_dir) / "public_datasets.json").read_text(encoding="utf-8"))
    return [d | {"verified_utc": doc["verified_utc"]} for d in doc["datasets"]]
